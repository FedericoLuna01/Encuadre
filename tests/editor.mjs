  console.log("PASS: live arrow, inline multiline text, keyboard editing, history and cancellation")
  assert.equal(await protectedEdits(), true)
  const reloadDialog = page.waitForEvent("dialog")
  await page.evaluate(() => { setTimeout(() => location.reload(), 0) })
  const dialog = await reloadDialog
  assert.equal(dialog.type(), "beforeunload")
  await dialog.dismiss()
  assert.match(await page.locator(".editor-footer").innerText(), /2 cambios/, "dismissed reload preserves the edit session")
  await page.getByRole("button", { name: "Deshacer", exact: true }).click(); await ready()
  await page.getByRole("button", { name: "Deshacer", exact: true }).click(); await ready()
