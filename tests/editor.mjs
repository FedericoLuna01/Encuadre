  await page.getByRole("button", { name: "Rehacer", exact: true }).click(); await ready()
  assert.equal(await protectedEdits(), true)
  // A failed download must not mark the current revision as saved.
  await page.evaluate(() => {
    window.originalAnchorClick = HTMLAnchorElement.prototype.click
    HTMLAnchorElement.prototype.click = () => { throw new Error("Test download failure") }
  })
