import { chromium } from "playwright"
import assert from "node:assert/strict"

const browser = await chromium.launch({ channel: "chromium", headless: true })
const origin = process.env.TEST_ORIGIN ?? "http://127.0.0.1:5175"
try {
  const page = await browser.newPage({ locale: "es-AR", viewport: { width: 1440, height: 1000 } })
  await page.goto(`${origin}/result.html`)
  await page.evaluate(async () => {
    const { saveCapture } = await import("/src/lib/store.ts")
    const canvas = document.createElement("canvas"); canvas.width = 800; canvas.height = 600
    const context = canvas.getContext("2d"); context.fillStyle = "white"; context.fillRect(0, 0, 800, 600)
    const blob = await new Promise(resolve => canvas.toBlob(resolve))
    await saveCapture({ id: "editor-interaction", blob, width: 800, height: 600, cssWidth: 800, cssHeight: 600, profile: null, url: "https://ejemplo.com", title: "Editor", tabId: 1, createdAt: new Date().toISOString(), kind: "full", warnings: [], partial: false })
  })
  await page.goto(`${origin}/result.html?id=editor-interaction`)
  await page.getByRole("button", { name: "Editar captura", exact: true }).click()
  const surface = page.getByRole("application", { name: "Lienzo de edición" })
  const ready = () => page.waitForFunction(() => document.querySelector(".editor-surface")?.getAttribute("aria-busy") === "false")
  await ready()
  await page.getByLabel("Flecha", { exact: true }).click()
  const box = await surface.boundingBox()
  await page.mouse.move(box.x + 40, box.y + 40); await page.mouse.down()
  await page.mouse.move(box.x + 180, box.y + 120, { steps: 8 })
  assert.equal(await surface.locator(".editor-selection").count(), 0, "An arrow must not preview as a rectangle")
  const preview = surface.locator("canvas")
  assert.equal(await preview.count(), 1, "Drawing must preview before pointer release")
  assert.ok(await preview.evaluate(canvas => canvas.getContext("2d").getImageData(0, 0, canvas.width, canvas.height).data.some((v, i) => i % 4 === 3 && v > 0)))
  await page.screenshot({ path: "test-results/editor-live-arrow.png" })
  await page.mouse.up(); await ready()
  await page.getByLabel("Texto", { exact: true }).click()
  assert.equal(await page.locator(".editor-controls textarea, #edit-text").count(), 0)
  await surface.click({ position: { x: 50, y: 170 } })
  const text = surface.getByRole("textbox", { name: "Texto a colocar" })
  await text.fill("Revisar menú ñ\nSegunda línea")
  await text.press("ArrowLeft"); await text.press("End")
  assert.equal(await text.inputValue(), "Revisar menú ñ\nSegunda línea")
  await page.screenshot({ path: "test-results/editor-inline-text.png" })
  await text.press("Enter"); await ready()
  assert.equal(await text.count(), 0)
  await page.getByRole("button", { name: "Deshacer", exact: true }).click(); await ready()
  await page.getByRole("button", { name: "Rehacer", exact: true }).click(); await ready()
  await surface.click({ position: { x: 70, y: 240 } })
  await text.fill("Cancelar"); await text.press("Escape")
  assert.equal(await text.count(), 0)
  assert.match(await page.locator(".editor-footer").innerText(), /2 cambios/)
  console.log("PASS: live arrow, inline multiline text, keyboard editing, history and cancellation")
  await page.evaluate(async () => {
    const { saveCapture, readCapture } = await import("/src/lib/store.ts")
    const { profiles } = await import("/src/lib/model.ts")
    const record = await readCapture("editor-interaction")
    await saveCapture({ ...record, id: "editor-frame", kind: "visible", profile: profiles.find(profile => profile.id === "iphone-13") })
  })
  await page.goto(`${origin}/result.html?id=editor-frame`)
  const frame = page.getByRole("radio", { name: "Con marco", exact: true })
  const download = page.getByRole("button", { name: "Descargar PNG", exact: true })
  await download.waitFor({ state: "visible" })
  await page.waitForFunction(() => !document.querySelector(".download-primary").disabled)
  const pixels = () => page.locator(".captured-image").evaluate(async image => {
    await image.decode()
    const canvas = document.createElement("canvas"); canvas.width = image.naturalWidth; canvas.height = image.naturalHeight
    canvas.getContext("2d").drawImage(image, 0, 0)
    return canvas.toDataURL()
  })
  const original = await pixels()
  await page.getByRole("button", { name: "Editar captura", exact: true }).click()
  await ready()
  await page.getByRole("button", { name: "Cancelar edición", exact: true }).click()
  await page.waitForFunction(() => !document.querySelector(".download-primary").disabled)
  assert.equal(await page.locator(".capture-editor").count(), 0)
  assert.equal(await frame.count(), 1, "cancelling without edits restores frame options")
  assert.equal(await frame.getAttribute("aria-checked"), "true")
  assert.equal(await pixels(), original)
  await page.getByRole("button", { name: "Editar captura", exact: true }).click()
  await ready()
  await page.getByLabel("Texto", { exact: true }).click()
  await surface.click({ position: { x: 30, y: 30 } })
  await text.fill("Descartar este texto")
  await text.press("Enter"); await ready()
  await page.getByRole("button", { name: "Ver resultado", exact: true }).click()
  await page.getByRole("button", { name: "Cancelar edición", exact: true }).click()
  await page.waitForFunction(() => !document.querySelector(".download-primary").disabled)
  assert.equal(await frame.count(), 1)
  assert.equal(await frame.getAttribute("aria-checked"), "true")
  assert.equal(await pixels(), original, "cancelling restores the original pixels")
  await page.getByRole("radio", { name: "Solo página", exact: true }).click()
  await page.getByRole("button", { name: "Editar captura", exact: true }).click(); await ready()
  assert.match(await page.locator(".editor-footer").innerText(), /Sin cambios/)
  await page.getByRole("button", { name: "Cancelar edición", exact: true }).click()
  await page.waitForFunction(() => !document.querySelector(".download-primary").disabled)
  assert.equal(await page.getByRole("radio", { name: "Solo página", exact: true }).getAttribute("aria-checked"), "true")
  console.log("PASS: cancelling an edit restores the frame and discards annotations and history")
} finally { await browser.close() }
