  const corner = crop.locator("[data-handle=se]")
  const cornerBox = await corner.boundingBox()
  await page.mouse.move(cornerBox.x + 8, cornerBox.y + 8); await page.mouse.down()
  await page.mouse.move(cornerBox.x + 8 - fullSize.width / 4, cornerBox.y + 8 - fullSize.height / 4, { steps: 5 }); await page.mouse.up()
