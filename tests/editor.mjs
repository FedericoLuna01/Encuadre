  await page.screenshot({ path: "test-results/editor-live-arrow.png" })
  await page.mouse.up(); await ready()
  await page.getByLabel("Texto", { exact: true }).click()
  assert.equal(await page.locator(".editor-controls textarea, #edit-text").count(), 0)
  await surface.click({ position: { x: 50, y: 170 } })
  const text = surface.getByRole("textbox", { name: "Texto a colocar" })
  await text.fill("Revisar menú ñ\nSegunda línea")
  await text.press("ArrowLeft"); await text.press("End")
  assert.equal(await text.inputValue(), "Revisar menú ñ\nSegunda línea")
