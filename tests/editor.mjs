  await page.getByRole("button", { name: "Ver resultado", exact: true }).click()
  await page.getByRole("button", { name: "Cancelar edición", exact: true }).click()
  await page.waitForFunction(() => !document.querySelector(".download-primary").disabled)
  assert.equal(await frame.count(), 1)
  assert.equal(await frame.getAttribute("aria-checked"), "true")
  assert.equal(await pixels(), original, "cancelling restores the original pixels")
  await page.getByRole("radio", { name: "Solo página", exact: true }).click()
  await page.getByRole("button", { name: "Editar captura", exact: true }).click(); await ready()
  assert.match(await page.locator(".editor-footer").innerText(), /Sin cambios/)
  await page.getByRole("button", { name: "Cancelar edición", exact: true }).click()
  await page.waitForFunction(() => !document.querySelector(".download-primary").disabled)
  assert.equal(await page.getByRole("radio", { name: "Solo página", exact: true }).getAttribute("aria-checked"), "true")
  console.log("PASS: cancelling an edit restores the frame and discards annotations and history")
  await page.evaluate(async () => {
    const { readCapture, saveCapture } = await import("/src/lib/store.ts")
    const record = await readCapture("editor-frame")
    await saveCapture({ ...record, id: "editor-interaction", kind: "full", profile: null })
  })
  await page.goto(`${origin}/result.html?id=editor-interaction`)
  await page.getByRole("button", { name: "Editar captura", exact: true }).waitFor()
  await page.context().grantPermissions(["clipboard-read", "clipboard-write"])
  await page.bringToFront()
  await page.keyboard.press("Control+c")
  await page.getByRole("button", { name: "Imagen copiada", exact: true }).waitFor()
  assert.deepEqual(await page.evaluate(async () => {
    const [item] = await navigator.clipboard.read()
    const image = await createImageBitmap(await item.getType("image/png"))
    const size = [image.width, image.height]; image.close(); return size
  }), [800, 600], "Ctrl+C writes a PNG to the real browser clipboard")
  await page.evaluate(() => {
    window.copiedSizes = []
    Object.defineProperty(navigator, "clipboard", { configurable: true, value: { write: async items => {
      if (window.failClipboard) throw new Error("Test clipboard failure")
      const blob = await items[0].getType("image/png")
      const image = await createImageBitmap(blob)
      window.copiedSizes.push([image.width, image.height]); image.close()
    } } })
  })
  await page.keyboard.press("Control+c")
  await page.waitForFunction(() => window.copiedSizes.length === 1)
  assert.deepEqual(await page.evaluate(() => window.copiedSizes[0]), [800, 600])
  await page.keyboard.press("Control+t"); await ready()
  const crop = surface.getByRole("group", { name: "Marco de recorte" })
  await crop.waitFor()
