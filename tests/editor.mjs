  await page.getByText("Test download failure", { exact: true }).waitFor()
  assert.equal(await protectedEdits(), true)
  await page.evaluate(() => { HTMLAnchorElement.prototype.click = window.originalAnchorClick; delete window.originalAnchorClick })
  const saved = page.waitForEvent("download")
  await page.getByRole("button", { name: "Descargar PNG", exact: true }).click()
  const downloaded = await saved
  assert.equal(await downloaded.failure(), null)
  assert.equal(await protectedEdits(), false, "initiating a download clears the warning")
  await page.getByRole("button", { name: "Rehacer", exact: true }).click(); await ready()
  assert.equal(await protectedEdits(), true, "editing after download warns again")
  await page.getByRole("button", { name: "Deshacer", exact: true }).click(); await ready()
  assert.equal(await protectedEdits(), false, "returning to the downloaded revision is clean")
  await page.getByRole("button", { name: "Rehacer", exact: true }).click(); await ready()
  await page.getByRole("button", { name: "Cancelar edición", exact: true }).click()
  assert.equal(await protectedEdits(), false, "cancelling the editing session removes the warning")
  console.log("PASS: native reload warning, undo/redo, failed and successful downloads, and cancellation")
  await page.evaluate(async () => {
    const { saveCapture, readCapture } = await import("/src/lib/store.ts")
    const { profiles } = await import("/src/lib/model.ts")
    const record = await readCapture("editor-interaction")
    await saveCapture({ ...record, id: "editor-frame", kind: "visible", profile: profiles.find(profile => profile.id === "iphone-13") })
  })
  await page.goto(`${origin}/result.html?id=editor-frame`)
  const frame = page.getByRole("radio", { name: "Con marco", exact: true })
  const download = page.getByRole("button", { name: "Descargar PNG", exact: true })
  await download.waitFor({ state: "visible" })
  await page.waitForFunction(() => !document.querySelector(".download-primary").disabled)
  const pixels = () => page.locator(".captured-image").evaluate(async image => {
    await image.decode()
    const canvas = document.createElement("canvas"); canvas.width = image.naturalWidth; canvas.height = image.naturalHeight
    canvas.getContext("2d").drawImage(image, 0, 0)
    return canvas.toDataURL()
  })
  const original = await pixels()
  await page.getByRole("button", { name: "Editar captura", exact: true }).click()
  await ready()
  await page.getByRole("button", { name: "Cancelar edición", exact: true }).click()
  await page.waitForFunction(() => !document.querySelector(".download-primary").disabled)
  assert.equal(await page.locator(".capture-editor").count(), 0)
  assert.equal(await frame.count(), 1, "cancelling without edits restores frame options")
  assert.equal(await frame.getAttribute("aria-checked"), "true")
  assert.equal(await pixels(), original)
  await page.getByRole("button", { name: "Editar captura", exact: true }).click()
  await ready()
  await page.getByLabel("Texto", { exact: true }).click()
  await surface.click({ position: { x: 30, y: 30 } })
